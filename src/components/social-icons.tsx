export function getSocialLinks(profile: Profile) {
  return [
    { label: "GitHub", href: profile.github_url, Icon: GitHub },
    { label: "LinkedIn", href: profile.linkedin_url, Icon: LinkedIn },
    { label: "X (Twitter)", href: profile.twitter_url, Icon: XLogo },
    { label: "Instagram", href: profile.instagram_url, Icon: Instagram },
    { label: "Website", href: profile.website_url, Icon: Globe },
    { label: "Email", href: profile.email ? `mailto:${profile.email}` : null, Icon: Mail },
  ].filter((l): l is { label: string; href: string; Icon: typeof GitHub } => Boolean(l.href));
}

export function SocialLinks({ profile, className }: { profile: Profile; className?: string }) {
  const links = getSocialLinks(profile);
  if (!links.length) return null;
  return (
    <ul className={cn("flex flex-wrap items-center gap-2", className)}>
      {links.map(({ label, href, Icon }) => (
        <li key={label}>
          <a
            href={href}
            target={href.startsWith("mailto:") ? undefined : "_blank"}
            rel="noopener noreferrer"
            aria-label={label}
            className="grid h-10 w-10 place-items-center rounded-full border border-border bg-card/50 text-muted-foreground backdrop-blur transition-all duration-300 hover:-translate-y-0.5 hover:border-primary/50 hover:bg-primary/10 hover:text-primary"
          >
            <Icon className="h-[18px] w-[18px]" />
          </a>
        </li>
      ))}
    </ul>
  );
}

